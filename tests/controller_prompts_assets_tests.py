"""Xbox controller prompt assets: the generated data, its identity against the installed game, the textures it produces, the
source art and its licence. The static checks need only the repository; the game checks read the installed pak (never write
it) and are skipped, and said to be, when it or numpy is missing.

    python tests/controller_prompts_assets_tests.py
"""
from __future__ import annotations

import os
import re
import subprocess
import sys
import time
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOOLS = ROOT / "tools" / "prompts"
DATA = ROOT / "src" / "sotb_prompt_assets_data.c"
GAME = ROOT / "game" / "prepared" / "CUSA03762-1.00"
PAK = GAME / "beast" / "content" / "paks" / "pakchunk0-ps4.pak"
BUILD = "CUSA03762-1.00"
GUEST = "/app0/beast/content/paks/pakchunk0-ps4.pak"

checks = 0
failures = 0
skipped: list[str] = []
_next_progress = 0.0


def check(condition: bool, message: str) -> None:
    global checks, failures, _next_progress
    checks += 1
    if "SOTB_TEST_PROGRESS" in os.environ and time.monotonic() >= _next_progress:
        _next_progress = time.monotonic() + 1.0
        print(f"@@sotb-progress checks={checks}", flush=True)
    if not condition:
        failures += 1
        print(f"FAIL: {message}")


def text(path: Path) -> str:
    return path.read_text(encoding="utf-8", errors="replace")


ASSET_ROW = re.compile(r'^\s*\{"(Beast/[^"]+)", (\d+)ull, (\d+), 0x([0-9a-f]{8})u, 0x([0-9a-f]{8})u, (\d+), (\d+), (\d+), (\d+), (\d+), (\d+)\},$', re.M)
RUN_ROW = re.compile(r"^\s*\{(\d+), (\d+), (\d+)\},$", re.M)


def parse_data(source: str):
    assets = [dict(name=m[0], offset=int(m[1]), size=int(m[2]), original=int(m[3], 16), replaced=int(m[4], 16), first=int(m[5]),
                   count=int(m[6]), fmt=int(m[7]), width=int(m[8]), height=int(m[9]), mips=int(m[10])) for m in ASSET_ROW.findall(source)]
    runs = [(int(a), int(b), int(c)) for a, b, c in RUN_ROW.findall(source)]
    start = source.index("static const unsigned char blob[] = {") + len("static const unsigned char blob[] = {")
    stream = bytes(int(v) for v in re.findall(r"\d+", source[start:source.index("};", start)]))
    header = re.search(r'\{"%s", "([^"]+)",\s*(\d+)ull, (\d+)ull, (\d+)u, 0x([0-9a-f]{8})u,' % re.escape(BUILD), source)
    tail = re.search(r"blob, (\d+), (\d+), 0x([0-9a-f]{8})u\}", source)
    return assets, runs, stream, header, tail


def png_text_chunks(data: bytes) -> str:
    """The text of every metadata chunk of a PNG (the pixel data is not text and is not searched)."""
    out, pos = [], 8
    while pos + 8 <= len(data):
        length = int.from_bytes(data[pos:pos + 4], "big")
        kind = data[pos + 4:pos + 8]
        if kind in (b"tEXt", b"iTXt", b"eXIf", b"zTXt"):
            out.append(data[pos + 8:pos + 8 + length].decode("latin-1"))
        pos += 12 + length
    return "\n".join(out)


def static_checks() -> tuple[list, list, bytes]:
    for name in ("build_controller_prompts.py", "sotb_pak.py", "sotb_texture.py", "xbox_assets.py", "xbox_glyphs.py", "xbox_diagrams.py", "xbox_start_map.py"):
        check((TOOLS / name).is_file(), f"generator file {name} is present")
    source = text(DATA)
    check(source.startswith("/* Generated by tools/prompts/build_controller_prompts.py"), "generated data says what generated it")
    assets, runs, stream, header, tail = parse_data(source)
    check(header is not None and header[1] == GUEST, "generated data belongs to the build's pak path")
    check(f'"{BUILD}"' in source, "generated data names the build identity")
    check(len(assets) >= 80 and len(runs) > len(assets), "generated data lists the assets and their runs")
    check(tail is not None, "generated data has its stream size and CRC-32")
    if tail:
        blob_size, blob_crc = int(tail[2]), int(tail[3], 16)
        check(int(tail[1]) == len(stream), "stored stream size matches the array")
        try:
            blob = zlib.decompress(stream, -15)
        except zlib.error:
            blob = b""
        check(len(blob) == blob_size and zlib.crc32(blob) & 0xFFFFFFFF == blob_crc, "stream inflates to the recorded size and CRC-32")
    else:
        blob = b""

    check(len(assets) == len(set(a["name"] for a in assets)), "asset names are unique")
    cursor = 0
    previous_end = 0
    for a in assets:
        check(a["first"] == cursor, f"{a['name']}: runs are consecutive")
        cursor += a["count"]
        check(a["count"] >= 1 and a["size"] > 0 and a["offset"] >= previous_end + 53, f"{a['name']}: asset is placed after the previous entry")
        previous_end = a["offset"] + a["size"]
        check(a["original"] != a["replaced"], f"{a['name']}: replacement differs from the original")
        end = 0
        for offset, length, blob_offset in runs[a["first"]:a["first"] + a["count"]]:
            check(length > 0 and offset >= end and offset + length <= a["size"] and blob_offset + length <= len(blob), f"{a['name']}: run fits its asset and the stream")
            end = offset + length
    check(cursor == len(runs), "every run belongs to one asset")

    # Source artwork and licence.
    art = ROOT / "assets" / "source" / "controller"
    png = art / "xbox-series-lineart.png"
    check(png.is_file() and png.read_bytes()[:8] == b"\x89PNG\r\n\x1a\n", "source controller art exists")
    licence = text(art / "LICENSE-Gamepad-Line-Art-Pack.txt")
    check("CC0 1.0" in licence and "waived all copyright" in licence and "trademark" in licence, "line art licence is present with its trademark note")
    sources = text(art / "SOURCES.md")
    check("gidedin" in sources and "CC0 1.0" in sources and "itch.io/gamepad-line-art-pack" in sources, "source file records author, licence and origin")
    notices = text(ROOT / "packaging" / "licenses" / "THIRD-PARTY-LICENSES.txt")
    check("Gamepad Line Art Pack" in notices and "gidedin" in notices and "CC0 1.0" in notices, "third-party notices carry the line art attribution")
    check("DejaVu Sans" in notices and "Bitstream Vera Fonts Copyright" in notices, "third-party notices carry the DejaVu licence")
    check((ROOT / "gpu" / "third_party" / "fonts" / "DejaVuSans.ttf").is_file(), "the glyph font is already part of the project")
    check(not (art / "xbox-series-lineart.svg").exists() or "C:\\" not in text(art / "xbox-series-lineart.svg"), "source art has no author machine paths")

    # No author-machine paths in anything generated or added, and no game assets in the repository.
    local = re.compile(r"[A-Za-z]:\\|[A-Za-z]:/[A-Za-z]|/Users/|/home/|SauloB|VisualStudio")
    for path in [DATA, *TOOLS.glob("*.py"), art / "SOURCES.md", art / "LICENSE-Gamepad-Line-Art-Pack.txt", ROOT / "docs" / "CONTROLLER_PROMPTS.md"]:
        check(not local.search(text(path)), f"{path.name} has no local path")
    check(not local.search(png_text_chunks(png.read_bytes())), "source art metadata has no local path")
    forbidden = {".pak", ".uasset", ".uexp", ".ubulk", ".umap", ".gnf", ".dds", ".sprx", ".prx"}
    tracked = subprocess.run(["git", "ls-files", "--cached", "--others", "--exclude-standard"], cwd=ROOT, capture_output=True, text=True).stdout.split("\n")
    check(not [f for f in tracked if Path(f).suffix.lower() in forbidden], "no game container or texture file is in the repository")
    check(all((ROOT / f).stat().st_size < 3_000_000 for f in tracked if f.startswith(("assets/source/", "src/sotb_prompt")) and (ROOT / f).is_file()),
          "prompt sources and generated data stay small")
    check(DATA.stat().st_size < 3_000_000, "generated data is under 3 MB")

    # The runtime does not use Python or an image library.
    for name in ("sotb_prompt_assets.c", "sotb_prompt_assets.h", "sotb_game_prompts.c", "sotb_game_prompts.h"):
        body = text(ROOT / "src" / name).lower()
        check("python" not in body and "pillow" not in body and "numpy" not in body, f"{name} does not depend on Python")
    cmake = text(ROOT / "CMakeLists.txt")
    check("sotb_prompt_assets_data.c" in cmake and "build_controller_prompts" not in cmake, "the build compiles the generated data and never runs the generator")
    return assets, runs, blob


def game_checks(assets: list, runs: list, blob: bytes) -> None:
    if not PAK.is_file():
        skipped.append("the installed pak is missing")
        return
    try:
        import numpy as np  # noqa: F401
    except ImportError:
        skipped.append("numpy is missing")
        return
    sys.path.insert(0, str(TOOLS))
    import sotb_pak
    import sotb_texture as tex
    import xbox_assets

    def texture_for(package: bytes, run_offset: int):
        pages = tex.textures(package)
        if len(pages) == 1:
            return pages[0]
        return next((t for t in pages if any(m.start <= run_offset < m.start + m.size for m in t.mips)), None)

    with sotb_pak.Pak(PAK) as pak:
        _assets, _runs, _stream, header, _tail = parse_data(text(DATA))
        identity = pak.identity
        check(header is not None and int(header[2]) == identity.file_size and int(header[3]) == identity.index_offset and int(header[4]) == identity.index_size
              and int(header[5], 16) == identity.index_crc32, "the pak is the recorded file: size, index position, index size and CRC-32")
        check(identity.index_offset + identity.index_size + 44 == identity.file_size, "the pak ends with its index and footer")
        hud = pak.read(pak.entry("Beast/Content/Blueprints/GameHUD.uasset"))
        check(b"ButtonIconFont" in hud and b"CutsceneSkip" in hud and b"ActionButtonPrompt" in hud,
              "the in-game cutscene skip and action prompts use the button icon font")
        names = set()
        for a in assets:
            entry = pak.entry(a["name"])
            original = pak.read(entry)
            names.add(a["name"])
            check(entry.data_offset == a["offset"] and entry.size == a["size"], f"{a['name']}: position and size match the pak entry")
            check(sotb_pak.crc32(original) == a["original"], f"{a['name']}: original CRC-32 matches the installed pak")
            texture = texture_for(original, runs[a["first"]][0])
            check(texture is not None, f"{a['name']}: runs belong to a texture in the package")
            if texture is None:
                continue
            check((texture.pixel_format, texture.width, texture.height, len(texture.mips)) ==
                  ({1: "PF_DXT1", 2: "PF_DXT5", 3: "PF_B8G8R8A8"}[a["fmt"]], a["width"], a["height"], a["mips"]), f"{a['name']}: format, size and mip count match")
            patched = bytearray(original)
            payload = []
            for start, end in sorted((m.start, m.start + m.size) for m in texture.mips):
                if payload and payload[-1][1] == start:
                    payload[-1] = (payload[-1][0], end)
                else:
                    payload.append((start, end))
            for offset, length, blob_offset in runs[a["first"]:a["first"] + a["count"]]:
                patched[offset:offset + length] = blob[blob_offset:blob_offset + length]
                check(any(start <= offset and offset + length <= end for start, end in payload), f"{a['name']}: run stays inside mip payload bytes")
            check(zlib.crc32(bytes(patched)) & 0xFFFFFFFF == a["replaced"], f"{a['name']}: replacement CRC-32 matches the runs applied to the original")
            check(len(patched) == len(original), f"{a['name']}: size unchanged")
            first_payload = min(start for start, _ in payload)
            check(bytes(patched[:first_payload]) == original[:first_payload], f"{a['name']}: package header and properties are untouched")
            replaced_texture = texture_for(bytes(patched), runs[a["first"]][0])
            check(replaced_texture == texture, f"{a['name']}: mip table is unchanged")
            for level in range(len(texture.mips)):
                mip = texture.mips[level]
                before = tex.decode_mip(original, texture, level)
                after = tex.decode_mip(bytes(patched), texture, level)
                check(after.shape == before.shape and after.shape[:2] == (mip.height, mip.width), f"{a['name']}: mip {level} decodes at {mip.width}x{mip.height}")
                columns, rows = (mip.width + texture.block - 1) // texture.block, (mip.height + texture.block - 1) // texture.block
                raw = bytes(patched[mip.start:mip.start + mip.size])
                logical = tex.untile(raw, columns, rows, texture.element_bytes)
                again = tex.tile(logical, columns, rows, texture.element_bytes)
                check(np.array_equal(tex.untile(again, columns, rows, texture.element_bytes), logical), f"{a['name']}: mip {level} survives a tiling round trip")
            top_before, top_after = tex.decode_mip(original, texture, 0), tex.decode_mip(bytes(patched), texture, 0)
            if texture.pixel_format != "PF_DXT1":
                visible_after = top_after[..., 3] > 8
                visible_before = top_before[..., 3] > 8
                check(visible_after.any() and (~visible_after).any(), f"{a['name']}: alpha has both opaque and transparent texels")
                if "/3DPanels/Controls/" not in a["name"] and "Options" not in a["name"] and visible_before.any():
                    rows_b, cols_b = np.where(visible_before.any(1))[0], np.where(visible_before.any(0))[0]
                    inside = visible_after[rows_b[0]:rows_b[-1] + 1, cols_b[0]:cols_b[-1] + 1].sum()
                    check(int(visible_after.sum()) == int(inside), f"{a['name']}: Xbox art stays inside the original footprint")
            if a["name"] == xbox_assets.FONT + ".uasset":
                mip = texture.mips[0]
                block = texture.block
                columns, rows = (mip.width + block - 1) // block, (mip.height + block - 1) // block
                boxes = xbox_assets._font_boxes(top_before)
                check({kind for _, kind in boxes} == {kind for *_, kind in xbox_assets.FONT_GLYPHS},
                      "the button icon font has a glyph box for every controller icon")
                check("face:B" in {kind for _, kind in boxes}, "the Circle glyph of the cutscene skip prompt is covered")
                check("face:X" in {kind for _, kind in boxes}, "the Square glyph of the attack prompt is covered")
                touched = np.zeros((rows, columns), dtype=bool)
                for (x0, y0, x1, y1), _ in boxes:
                    touched[max(0, y0 - 1) // block:(y1 + 1 + block - 1) // block,
                            max(0, x0 - 1) // block:(x1 + 1 + block - 1) // block] = True
                before_blocks = tex.untile(original[mip.start:mip.start + mip.size], columns, rows, texture.element_bytes).reshape(rows, columns, -1)
                after_blocks = tex.untile(bytes(patched)[mip.start:mip.start + mip.size], columns, rows, texture.element_bytes).reshape(rows, columns, -1)
                changed = np.any(before_blocks != after_blocks, axis=2)
                check(not (changed & ~touched).any(), "the button icon font changes only the controller glyph blocks")
                for (x0, y0, x1, y1), kind in boxes:
                    before_box, after_box = top_before[y0:y1, x0:x1], top_after[y0:y1, x0:x1]
                    check(np.any(before_box != after_box), f"{a['name']}: {kind} is redrawn")
                    if kind.startswith("face:"):
                        pixels = after_box[..., :3].astype(np.int32)
                        saturated = (pixels.max(2) - pixels.min(2)) > 60
                        r, g, b = pixels[saturated].mean(0) if saturated.any() else (0, 0, 0)
                        hue = {"face:A": g > r + 20 and g > b + 20, "face:B": r > g + 20 and r > b + 20,
                               "face:X": b > r + 20 and b > g + 20, "face:Y": r > b + 20 and g > b + 20}[kind]
                        check(hue, f"{a['name']}: {kind} uses the Xbox button colour")
        check(len(names) == len(assets), "every asset is distinct")

        # Every prompt the game draws has an Xbox glyph.
        wanted = {name + ".uasset" for name, *_ in xbox_assets._glyph_specs()}
        kinds = {kind for _, kind, *_ in xbox_assets._glyph_specs()}
        check(wanted <= names, "every glyph the generator knows is in the generated data")
        for kind in ("face:A", "face:B", "face:X", "face:Y", "bumper:LB", "bumper:RB", "trigger:LT", "trigger:RT", "click:L", "click:R", "clicks", "menu", "view", "dpad"):
            check(kind in kinds, f"glyph {kind} is generated")
        by_name = {name: kind for name, kind, *_ in xbox_assets._glyph_specs()}
        hud = xbox_assets.CONTENT + "HUD/Textures/"
        expected = {"ButtonCross": "face:A", "ButtonCircle": "face:B", "ButtonSquare": "face:X", "ButtonTriangle": "face:Y", "ButtonL1": "bumper:LB",
                    "ButtonR1": "bumper:RB", "ButtonL2": "trigger:LT", "ButtonR2": "trigger:RT", "ButtonL3": "click:L", "ButtonR3": "click:R",
                    "ButtonOptions": "menu", "ButtonTouchpad": "view", "DPad_4Way": "dpad", "ButtonL3andR3": "clicks"}
        for asset, kind in expected.items():
            check(by_name.get(hud + asset) == kind, f"{asset} is drawn as {kind}")
        for asset in ("ButtonCross", "ButtonL1", "ButtonTouchpad", "ButtonOptions", "ButtonL3andR3"):
            check(hud + asset + "Pressed" in by_name, f"{asset} has a pressed Xbox variant")
        for needed in ("Beast/Content/HUD/PressStartScreen/ControllerMapStart", xbox_assets.CONTENT + "Frontend/OptionsScreen/Textures/3DPanels/Controls/controller",
                       xbox_assets.FONT):
            check(needed + ".uasset" in names, f"{needed.rsplit('/', 1)[-1]} is replaced")
        lines = [n for n in names if "/3DPanels/Controls/line" in n]
        check(len(lines) == 15, "all 15 caption lines of the Controller Settings diagram are replaced")

        # The generator reproduces the file on disk.
        # A toolchain folder on PATH can put other DLLs in front of the image library's own and change the drawn pixels.
        clean = dict(os.environ, PATH=os.pathsep.join(p for p in os.environ.get("PATH", "").split(os.pathsep) if "msys" not in p.lower()))
        run = subprocess.run([sys.executable, str(TOOLS / "build_controller_prompts.py"), "--game", str(GAME), "--check"], capture_output=True, text=True, env=clean)
        check(run.returncode == 0, "regenerating the data gives the file on disk: " + (run.stdout + run.stderr).strip()[-200:])


def main() -> int:
    assets, runs, blob = static_checks()
    game_checks(assets, runs, blob)
    for reason in skipped:
        print(f"SKIPPED game checks: {reason}")
    print(f"controller prompts assets tests: {checks} checks, {failures} failures")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
