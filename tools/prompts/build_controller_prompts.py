#!/usr/bin/env python3
"""Builds the Xbox controller prompt data of Shadow of the Beast from the installed game.

    python tools/prompts/build_controller_prompts.py --game game/prepared/CUSA03762-1.00
    python tools/prompts/build_controller_prompts.py --game game/prepared/CUSA03762-1.00 --check
    python tools/prompts/build_controller_prompts.py --game game/prepared/CUSA03762-1.00 --preview scratch/prompts

The output (src/sotb_prompt_assets_data.c) holds, per texture, the CRC-32 of the original package data and the bytes that
replace parts of it. The runtime applies them over the unchanged pak and never needs Python.
"""
from __future__ import annotations

import argparse
import os
import re
import sys
import zlib
from pathlib import Path

# Libraries of an MSYS2 toolchain found through PATH can replace the ones numpy and Pillow ship and change the encoded bytes.
os.environ["PATH"] = os.pathsep.join(p for p in os.environ.get("PATH", "").split(os.pathsep) if "msys" not in p.lower())

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))

import sotb_texture as tex
import xbox_assets as assets
import xbox_diagrams
import xbox_start_map
from sotb_pak import BUILD_KEY, ENTRY_HEADER_SIZE, PAK0_GUEST, PAK0_RELATIVE, Pak, crc32

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "src" / "sotb_prompt_assets_data.c"
RUN_GAP = 24
FORMAT_ID = {"PF_DXT1": 1, "PF_DXT5": 2, "PF_B8G8R8A8": 3}
BLOB_MARKER = "static const unsigned char blob[] = {"
BLOB_END = "};"


def collect(pak: Pak) -> list[assets.Replacement]:
    out = assets.glyph_replacements(pak)
    out.append(assets.font_replacement(pak))
    out += xbox_diagrams.diagram_replacements(pak)
    out.append(xbox_start_map.start_map_replacement(pak))
    names = [r.name for r in out]
    if len(set(names)) != len(names):
        raise SystemExit("an asset is replaced twice")
    for r in out:
        if len(r.original) != len(r.replaced):
            raise SystemExit(f"{r.name}: the replacement does not fit its slot")
    return sorted(out, key=lambda r: pak.entry(r.name + ".uasset").offset)


def payload_intervals(texture: tex.Texture) -> list[tuple[int, int]]:
    """The mip payload bytes of a package, adjacent payloads joined: the only bytes a replacement may change."""
    out: list[tuple[int, int]] = []
    for start, end in sorted((m.start, m.start + m.size) for m in texture.mips):
        if out and out[-1][1] == start:
            out[-1] = (out[-1][0], end)
        else:
            out.append((start, end))
    return out


def runs_between(original: bytes, replaced: bytes, texture: tex.Texture) -> list[tuple[int, int]]:
    """Runs of changed bytes; nearby changes join, but never across bytes that are not mip payload."""
    intervals = payload_intervals(texture)
    changed = np.flatnonzero(np.frombuffer(original, np.uint8) != np.frombuffer(replaced, np.uint8))
    runs: list[list[int]] = []
    last_interval = -1
    for index in changed.tolist():
        interval = next((i for i, (start, end) in enumerate(intervals) if start <= index < end), None)
        if interval is None:
            raise SystemExit("a replacement changes bytes outside the mip payload")
        if runs and interval == last_interval and index - runs[-1][1] <= RUN_GAP:
            runs[-1][1] = index + 1
        else:
            runs.append([index, index + 1])
        last_interval = interval
    return [(start, end - start) for start, end in runs]


def generator_environment() -> str:
    import PIL
    from PIL import features

    return f"Pillow {PIL.__version__} (FreeType {features.version('freetype2')}), numpy {np.__version__}"


def emit(pak: Pak, replacements: list[assets.Replacement]) -> str:
    blob = bytearray()
    run_rows, asset_rows = [], []
    for r in replacements:
        entry = pak.entry(r.name + ".uasset")
        runs = runs_between(r.original, r.replaced, r.texture)
        first = len(run_rows)
        for start, length in runs:
            run_rows.append((start, length, len(blob)))
            blob += r.replaced[start:start + length]
        patched = bytearray(r.original)
        for start, length in runs:
            patched[start:start + length] = r.replaced[start:start + length]
        if bytes(patched) != r.replaced:
            raise SystemExit(f"{r.name}: runs do not rebuild the replacement")
        t = r.texture
        asset_rows.append((r.name + ".uasset", entry.data_offset, len(r.original), crc32(r.original), crc32(r.replaced), first, len(runs),
                           FORMAT_ID[t.pixel_format], t.width, t.height, len(t.mips)))
    compressor = zlib.compressobj(9, zlib.DEFLATED, -15, 9)
    stored = compressor.compress(bytes(blob)) + compressor.flush()
    identity = pak.identity
    identity = pak.identity
    lines = [
        "/* Generated by tools/prompts/build_controller_prompts.py from the installed game. Do not edit. */",
        '#include "sotb_prompt_assets.h"',
        "",
        f"/* {len(asset_rows)} textures, {len(run_rows)} runs, {len(blob)} replacement bytes ({len(stored)} stored). */",
        f"/* Generator: {generator_environment()} */",
        BLOB_MARKER,
    ]
    for i in range(0, len(stored), 48):
        lines.append("    " + ",".join(str(b) for b in stored[i:i + 48]) + ",")
    lines += [BLOB_END, "", "static const SotbPromptRun runs[] = {"]
    lines += [f"    {{{s}, {n}, {o}}}," for s, n, o in run_rows]
    lines += ["};", "", "static const SotbPromptAsset assets[] = {"]
    for name, offset, size, original, replaced, first, count, fmt, width, height, mips in asset_rows:
        lines.append(f'    {{"{name}", {offset}ull, {size}, 0x{original:08x}u, 0x{replaced:08x}u, {first}, {count}, {fmt}, {width}, {height}, {mips}}},')
    lines += [
        "};",
        "",
        "const SotbPromptSet sotb_prompt_sets[] = {",
        f'    {{"{BUILD_KEY}", "{PAK0_GUEST}",',
        f"     {identity.file_size}ull, {identity.index_offset}ull, {identity.index_size}u, 0x{identity.index_crc32:08x}u,",
        "     assets, sizeof(assets) / sizeof(*assets), runs, sizeof(runs) / sizeof(*runs),",
        f"     blob, {len(stored)}, {len(blob)}, 0x{crc32(bytes(blob)):08x}u}},",
        "};",
        "const size_t sotb_prompt_set_count = sizeof(sotb_prompt_sets) / sizeof(*sotb_prompt_sets);",
        "",
    ]
    return "\n".join(lines)


def without_stream(text: str) -> str:
    head, _, rest = text.partition(BLOB_MARKER)
    text = head + rest.partition(BLOB_END)[2]
    return re.sub(r"\(\d+ stored\)|blob, \d+,", "", text)


def identity_view(text: str) -> str:
    """What identifies the game and the textures, without the pixels the generator drew (which depend on the image library)."""
    assets = re.findall(r'^\s*\{("Beast/[^"]+", \d+ull, \d+, 0x[0-9a-f]{8}u), 0x[0-9a-f]{8}u, \d+, \d+, (\d+, \d+, \d+, \d+)\},$', text, re.M)
    header = re.search(r'\{"[^"]+", "[^"]+",\s*\d+ull, \d+ull, \d+u, 0x[0-9a-f]{8}u,', text)
    return "\n".join([header.group(0) if header else ""] + [f"{a} {b}" for a, b in assets])


def environment_of(text: str) -> str:
    match = re.search(r"/\* Generator: (.*) \*/", text)
    return match.group(1) if match else ""


def preview(replacements: list[assets.Replacement], folder: Path) -> None:
    from PIL import Image

    folder.mkdir(parents=True, exist_ok=True)
    for r in replacements:
        base = r.name.rsplit("/", 1)[-1]
        stem = r.name.replace(assets.CONTENT, "").replace("/", "_")
        for label, data in (("xbox", r.replaced),):
            image = tex.decode_mip(data, r.texture, 0)
            canvas = Image.new("RGBA", (image.shape[1], image.shape[0]), (58, 58, 66, 255))
            canvas.alpha_composite(Image.fromarray(image, "RGBA"))
            canvas.convert("RGB").save(folder / f"{stem}_{label}.png")
        del base


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--game", type=Path, default=ROOT / "game" / "prepared" / BUILD_KEY)
    parser.add_argument("--out", type=Path, default=OUT)
    parser.add_argument("--check", action="store_true", help="fail when the output differs from the file on disk")
    parser.add_argument("--preview", type=Path, help="write PNG inspection images (developer use only)")
    args = parser.parse_args()
    with Pak(args.game / PAK0_RELATIVE) as pak:
        replacements = collect(pak)
        text = emit(pak, replacements)
        if args.preview:
            preview(replacements, args.preview)
    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.exists() else ""
        # The deflate stream may differ between zlib versions, and the drawn pixels between image libraries; everything
        # that identifies the game and the textures may not differ in any environment.
        if environment_of(current) == environment_of(text):
            same = without_stream(current) == without_stream(text)
            note = ""
        else:
            same = identity_view(current) == identity_view(text)
            note = f" (identity only: generated with {environment_of(current) or 'an unknown environment'}, this is {environment_of(text)})"
        if not same:
            print("generated data differs from", args.out)
            return 1
        print(f"{len(replacements)} textures match {args.out.name}{note}")
        return 0
    args.out.write_text(text, encoding="utf-8", newline="\n")
    print(f"{len(replacements)} textures -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
